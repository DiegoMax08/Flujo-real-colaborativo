print("Análisis estadístico de datos")

datos = [10, 20, 30, 40, 50]

maximo = max(datos)
print("Máximo:", maximo)

minimo = min(datos)
print("Mínimo:", minimo)

rango = max(datos) - min(datos)
print("Rango:", rango)

print("Datos:", datos)

suma = sum(datos)
print("Suma:", suma)

promedio = sum(datos) / len(datos)
print("Promedio:", promedio)

cantidad = len(datos)
print("Cantidad de datos:", cantidad)

print("\n--- Resultados del análisis ---")
